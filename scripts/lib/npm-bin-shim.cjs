#!/usr/bin/env node
"use strict";

/**
 * Front door bin shim for the npm distribution of Prime Agent.
 *
 * The executable itself lives in a per-platform package (esbuild model): the front door declares all
 * four platform packages as `optionalDependencies` pinned to the exact version, and npm/pnpm/yarn/bun
 * install only the one whose `os`/`cpu` fields match. There is no postinstall script, so nothing is
 * downloaded or executed at install time; this shim only locates the already installed binary.
 *
 * The platform map (and the executable SHA-256 receipt for each platform) is read from the front
 * door's own package.json, which is generated by scripts/pack-npm-packages.mjs.
 */

const { spawnSync } = require("node:child_process");
const { createHash } = require("node:crypto");
const { accessSync, chmodSync, constants, existsSync, readFileSync, statSync } = require("node:fs");
const { dirname, join, parse } = require("node:path");

const manifest = require("../package.json");
const platforms = (manifest.primeAgent && manifest.primeAgent.platforms) || {};
const key = `${process.platform}-${process.arch}`;

function fail(message) {
	process.stderr.write(`prime-agent: ${message}\n`);
	process.exit(1);
}

function supported() {
	return Object.keys(platforms).sort().join(", ") || "(none)";
}

/**
 * Resolve the platform package directory. `require.resolve` covers node, npm, pnpm and yarn PnP.
 * The manual node_modules walk covers layouts where resolution from this file is restricted
 * (for example a hoisted install inspected through a symlinked path).
 */
function platformPackageDir(packageName) {
	try {
		return dirname(require.resolve(`${packageName}/package.json`));
	} catch {}
	const segments = packageName.split("/");
	let directory = __dirname;
	const root = parse(directory).root;
	while (true) {
		const candidate = join(directory, "node_modules", ...segments);
		if (existsSync(join(candidate, "package.json"))) return candidate;
		if (directory === root) return undefined;
		const parent = dirname(directory);
		if (parent === directory) return undefined;
		directory = parent;
	}
}

function ensureExecutable(binary) {
	try {
		accessSync(binary, constants.X_OK);
		return;
	} catch {}
	try {
		chmodSync(binary, 0o755);
	} catch {}
}

function verifyReceipt(packageDir, binary, expected) {
	if (!expected) fail(`missing executable receipt for ${key}; refusing to run`);
	const receiptPath = join(packageDir, "receipts.json");
	if (existsSync(receiptPath)) {
		const receipt = JSON.parse(readFileSync(receiptPath, "utf8"));
		if (receipt.executableSha256 !== expected) {
			fail(`receipt mismatch for ${key}: ${receiptPath} does not match the front door package metadata`);
		}
	}
	const actual = createHash("sha256").update(readFileSync(binary)).digest("hex");
	if (actual !== expected) fail(`executable hash mismatch for ${key}: expected ${expected}, found ${actual}`);
}

function main() {
	const override = process.env.PRIME_AGENT_NPM_BINARY;
	if (override) {
		if (!existsSync(override)) fail(`PRIME_AGENT_NPM_BINARY does not exist: ${override}`);
		return run(override);
	}

	const entry = platforms[key];
	if (!entry) {
		fail(
			`unsupported platform ${key}. Prime Agent ships npm binaries for: ${supported()}.\n` +
				"  Install another way: curl -fsSL https://install.prime-agent.dev | sh",
		);
	}

	const packageDir = platformPackageDir(entry.package);
	if (!packageDir) {
		fail(
			`the platform package ${entry.package} is not installed.\n` +
				"  This usually means optional dependencies were skipped (--no-optional, --omit=optional,\n" +
				"  or a lockfile created on a different platform). Reinstall with optional dependencies, or run:\n" +
				`    npm install ${entry.package}@${manifest.version}`,
		);
	}

	const binary = join(packageDir, entry.binary || join("bin", "prime-agent"));
	if (!existsSync(binary) || !statSync(binary).isFile()) {
		fail(`the platform package ${entry.package} is installed but ${binary} is missing`);
	}
	ensureExecutable(binary);
	if (process.env.PRIME_AGENT_VERIFY_BINARY === "1") verifyReceipt(packageDir, binary, entry.executableSha256);
	run(binary);
}

function run(binary) {
	const result = spawnSync(binary, process.argv.slice(2), { stdio: "inherit" });
	if (result.error) fail(`failed to execute ${binary}: ${result.error.message}`);
	if (result.signal) {
		process.kill(process.pid, result.signal);
		return;
	}
	process.exit(result.status === null ? 1 : result.status);
}

main();
